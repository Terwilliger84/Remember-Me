    fun byId(mode: String?): AppThemeSpec {
        val clean = when (mode?.trim()?.lowercase()) {
            null, "", "light" -> "warm"
            "dark" -> "cozy-dark"
            else -> mode.trim().lowercase()
        }
        return ALL.firstOrNull { it.id == clean } ?: ALL.first()
    }

    fun nextMode(current: String?): String {
        val spec = byId(current)
        val idx = ALL.indexOfFirst { it.id == spec.id }
        return ALL[(idx + 1) % ALL.size].id
    }
